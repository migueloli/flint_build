#[test]
fn test_plugins_share_one_file_in_config_order() {
    let package = Package::new(
        "plugins:\n  describe:\n    class_annotations: [\"@JsonSerializable\"]\n    template_path: describe.tera\n  flint_json:\n",
    );
    package.write(
        "describe.tera",
        "// GENERATED CODE - DO NOT MODIFY BY HAND\n\npart of '{{ filename }}';\n\n{% for class in classes %}// describes {{ class.name }}\n{% endfor %}",
    );
    package.write("lib/user.dart", USER);

    package.build(false);
    let first = package.read("lib/user.g.dart");
    for _ in 0..10 {
        package.build(true);
        assert_eq!(package.read("lib/user.g.dart"), first);
    }

    let describe = first.find("// describes User").unwrap();
    let json = first.find("_$UserFromJson").unwrap();
    assert!(describe < json, "sections must follow flint.yaml order");
    assert_eq!(first.matches("part of 'user.dart';").count(), 1);
    assert_eq!(first.matches("DO NOT MODIFY BY HAND").count(), 1);
}

#[test]
