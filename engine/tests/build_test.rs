//! End-to-end tests for output ownership (spec 0001), run against a temporary Dart package.

use flint_build::builder::{BuildReport, build, clean};
use flint_build::config::Pubspec;
use flint_build::generators::flint_json::emitter::FlintJsonGenerator;
use flint_build::output;
use flint_build::registry::PluginRegistry;
use std::fs;
use std::path::PathBuf;
use std::time::{Duration, SystemTime};
use tempfile::TempDir;

const USER: &str = "part 'user.g.dart';

@JsonSerializable()
class User {
  final int id;
  User({required this.id});
}
";

const FOREIGN: &str = "// GENERATED CODE - DO NOT MODIFY BY HAND\n\npart of 'x.dart';\n\n// written by another generator\n";

struct Package {
    dir: TempDir,
}

impl Package {
    fn new(flint_yaml: &str) -> Self {
        let dir = tempfile::tempdir().unwrap();
        fs::create_dir(dir.path().join("lib")).unwrap();
        fs::write(dir.path().join("flint.yaml"), flint_yaml).unwrap();
        Package { dir }
    }

    fn json() -> Self {
        Self::new("plugins:\n  flint_json:\n")
    }

    fn path(&self, relative: &str) -> PathBuf {
        self.dir.path().join(relative)
    }

    fn write(&self, relative: &str, content: &str) {
        fs::write(self.path(relative), content).unwrap();
    }

    fn read(&self, relative: &str) -> String {
        fs::read_to_string(self.path(relative)).unwrap()
    }

    fn exists(&self, relative: &str) -> bool {
        self.path(relative).exists()
    }

    fn set_mtime(&self, relative: &str, seconds_after_epoch: u64) {
        let file = fs::File::options()
            .write(true)
            .open(self.path(relative))
            .unwrap();
        file.set_modified(SystemTime::UNIX_EPOCH + Duration::from_secs(seconds_after_epoch))
            .unwrap();
    }

    /// Makes an output look older than its source, so the mtime check can't skip it.
    fn age(&self, relative: &str) {
        self.set_mtime(relative, 1);
    }

    fn build(&self, force: bool) -> BuildReport {
        let mut registry = PluginRegistry::new();
        registry.register("flint_json", Box::new(FlintJsonGenerator));
        let pubspec: Pubspec = "name: app\n".parse().unwrap();
        build(self.dir.path(), &pubspec, force, &registry).unwrap()
    }
}

#[test]
fn test_writes_owned_output_for_annotated_source() {
    let package = Package::json();
    package.write("lib/user.dart", USER);

    let report = package.build(false);

    assert_eq!(report.written, vec![package.path("lib/user.g.dart")]);
    assert!(report.errors.is_empty() && report.warnings.is_empty());
    let generated = package.read("lib/user.g.dart");
    assert!(generated.contains("part of 'user.dart';"));
    assert!(generated.contains("_$UserFromJson"));
    assert!(output::is_owned(&package.path("lib/user.g.dart")).unwrap());
}

#[test]
fn test_clean_leaves_files_flint_did_not_write() {
    let package = Package::json();
    package.write("lib/user.dart", USER);
    package.build(false);
    package.write("lib/other.g.dart", FOREIGN);

    let report = clean(package.dir.path()).unwrap();

    assert_eq!(report.deleted, vec![package.path("lib/user.g.dart")]);
    assert_eq!(report.skipped, vec![package.path("lib/other.g.dart")]);
    assert!(!package.exists("lib/user.g.dart"));
    assert_eq!(package.read("lib/other.g.dart"), FOREIGN);
}

